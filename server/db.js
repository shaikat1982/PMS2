// Calendar days ("today", "due this week") follow the server's time zone unless APP_TIMEZONE is set.
const zone = process.env.APP_TIMEZONE || Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC';
export const TIMEZONE = /^[A-Za-z0-9_/+-]+$/.test(zone) ? zone : 'UTC';

// Keep the API's existing formats: DATE → "YYYY-MM-DD", TIMESTAMPTZ → UTC "YYYY-MM-DD HH:MM:SS",
// and counts / sums (bigint, numeric) → plain numbers.
const { types } = pg;
types.setTypeParser(types.builtins.DATE, (v) => v);
types.setTypeParser(types.builtins.TIMESTAMPTZ, (v) => new Date(v).toISOString().slice(0, 19).replace('T', ' '));
types.setTypeParser(types.builtins.INT8, (v) => Number(v));
types.setTypeParser(types.builtins.NUMERIC, (v) => Number(v));

// One pool per process. Next.js dev mode re-evaluates modules on every change, so the
// pool is kept on globalThis instead of being recreated (and leaking connections).
export const pool = globalThis.__instacallPool ??= new pg.Pool({
  connectionString: DATABASE_URL,
  max: Number(process.env.DATABASE_POOL_SIZE) || 10,
  ssl: process.env.DATABASE_SSL === 'true' ? { rejectUnauthorized: process.env.DATABASE_SSL_REJECT_UNAUTHORIZED !== 'false' } : undefined,
});

/** SQL for the calendar day of a timestamp column in the app's time zone. */
export const localDay = (column) => `(${column} AT TIME ZONE '${TIMEZONE}')::date`;
if (!pool.listenerCount('error')) pool.on('error', (err) => console.error('PostgreSQL connection error:', err.message));

// Queries are written with "?" placeholders; they become $1, $2… here (skipping quoted text).
const converted = new Map();
function toPg(sql) {
  let out = converted.get(sql);
  if (out) return out;
  let n = 0;
  let quoted = false;
  out = '';
  for (const ch of sql) {
    if (ch === "'") quoted = !quoted;
    out += ch === '?' && !quoted ? `$${++n}` : ch;
  }
  converted.set(sql, out);
  return out;
}

const clean = (params) => params.map((p) => (p === undefined ? null : p));

// Inside tx(), every query in the same async flow runs on the transaction's connection.
// A connection runs one query at a time, so queries there are chained in order (helpers
// may still fire several at once with Promise.all).
const txStore = new AsyncLocalStorage();

function query(text, params) {
  const t = txStore.getStore();
  if (!t) return pool.query(text, params);
  const result = t.chain.then(() => t.client.query(text, params));
  t.chain = result.catch(() => {});
  return result;
}

export async function all(sql, ...params) {
  return (await query(toPg(sql), clean(params))).rows;
}

export async function get(sql, ...params) {
  return (await query(toPg(sql), clean(params))).rows[0];
}

export async function run(sql, ...params) {
  const res = await query(toPg(sql), clean(params));
  return { changes: res.rowCount, rows: res.rows };
}

/** INSERT … and return the new row's id. */
export async function insert(sql, ...params) {
  return Number((await query(`${toPg(sql)} RETURNING id`, clean(params))).rows[0].id);
}

/** Run fn in a transaction. Nested calls join the outer transaction. */
export async function tx(fn) {
  if (txStore.getStore()) return fn();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await txStore.run({ client, chain: Promise.resolve() }, fn);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

